import { CaseDescriptionWindowData } from './types';

type CaseSeed = Omit<CaseDescriptionWindowData, 'caseType'>;

function toKeywordSignals(includeSignals: string[], excludeSignals: string[]): string[] {
  return [...includeSignals, ...excludeSignals.map(signal => `exclude:${signal}`)];
}

function toClassificationBasis(includeSignals: string[], excludeSignals: string[]): string {
  const includeText = includeSignals.length > 0 ? includeSignals.join(', ') : '명시 키워드 없음';
  const excludeText = excludeSignals.length > 0 ? excludeSignals.join(', ') : '제외 키워드 없음';
  return `title/body/publisher 텍스트에서 포함 신호(${includeText})를 먼저 찾고, 제외 신호(${excludeText})와 충돌하지 않을 때 이 유형으로 분류한다.`;
}

function buildCase(caseType: string, seed: CaseSeed): CaseDescriptionWindowData {
  const keywordSignals = seed.keywordSignals ?? toKeywordSignals(seed.includeSignals, seed.excludeSignals);
  const classificationBasis = seed.classificationBasis ?? toClassificationBasis(seed.includeSignals, seed.excludeSignals);
  return {
    caseType,
    keywordSignals,
    classificationBasis,
    ...seed,
  };
}

function aliasCase(caseType: string, base: CaseDescriptionWindowData, overrides?: Partial<CaseSeed>): CaseDescriptionWindowData {
  return {
    ...base,
    ...overrides,
    keywordSignals: overrides?.keywordSignals ?? base.keywordSignals,
    classificationBasis: overrides?.classificationBasis ?? base.classificationBasis,
    caseType,
  };
}

